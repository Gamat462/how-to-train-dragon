-- senja.sql — basis data latihan jalur SQL Mahir (PostgreSQL 12+)
-- Jalankan sekali di database kosong bernama senja.
DROP TABLE IF EXISTS item, pesanan, kunjungan, pesanan_kasir, pelanggan, produk, pegawai;

CREATE TABLE pelanggan (
  id             integer PRIMARY KEY,
  nama           text,
  kota           text,
  tanggal_daftar date,
  id_perujuk     integer
);
CREATE TABLE produk (
  id         integer PRIMARY KEY,
  nama       text,
  kategori   text,
  harga      integer,
  harga_beli integer
);
CREATE TABLE pegawai (
  id        integer PRIMARY KEY,
  nama      text,
  jabatan   text,
  cabang    text,
  id_atasan integer,
  gaji      integer
);
CREATE TABLE pesanan (
  id           integer PRIMARY KEY,
  pelanggan_id integer,
  tanggal      date,
  cabang       text,
  kanal        text,
  status       text
);
CREATE TABLE item (
  id             integer PRIMARY KEY,
  pesanan_id     integer,
  produk_id      integer,
  jumlah         integer,
  harga_saat_itu integer
);
CREATE TABLE kunjungan (
  id           integer PRIMARY KEY,
  pelanggan_id integer,
  waktu        timestamp
);
CREATE TABLE pesanan_kasir (
  id      integer PRIMARY KEY,
  tanggal date,
  cabang  text,
  nilai   integer
);


